export async function ensureSources(db: Db) {
  for (const r of sources)
    await db.query(
      `INSERT INTO tariff_source_registry(code,region,countries,name,url,access_type,hs_level,authority,notes,requirements,enabled,status,checked_at,check_evidence) VALUES(${Array.from({ length: 14 }, (_, i) => "$" + (i + 1)).join(",")}) ON CONFLICT(code) DO NOTHING`,
      [
        ...r,
        sourceChecks[r[0]]?.checkedAt || null,
        JSON.stringify(sourceChecks[r[0]] || {}),
      ],
    );
}
